/**
 * Returns a guaranteed exact photo matching the German vocabulary word.
 */
export function getVocabularyImage(vocab: {
  word?: string;
  meaningEn?: string;
  topic?: string;
  imageUrl?: string;
}): string {
  // 1. Dynamic database-supplied image (from MongoDB / API)
  if (vocab.imageUrl && typeof vocab.imageUrl === 'string' && vocab.imageUrl.trim().length > 0) {
    return vocab.imageUrl.trim();
  }

  const rawWord = (vocab.word || '').trim().toLowerCase();

  // Strip articles (der/die/das/ein/eine) and non-word characters
  const cleanWord = rawWord
    .replace(/^(der|die|das|dem|den|des|ein|eine|einen|einem|eines)s+/i, '')
    .replace(/[.,/#!$%^&*;:{}=\-_~`()]/g, '')
    .trim();

  // 2. Exact match in German word dictionary
  if (EXACT_VOCABULARY_IMAGES[cleanWord]) {
    return EXACT_VOCABULARY_IMAGES[cleanWord];
  }

  // 3. Normalized umlauts match
  const noUmlauts = cleanWord
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss');

  if (EXACT_VOCABULARY_IMAGES[noUmlauts]) {
    return EXACT_VOCABULARY_IMAGES[noUmlauts];
  }

  // 4. Exact match inside cleanWord compound
  for (const [key, url] of Object.entries(EXACT_VOCABULARY_IMAGES)) {
    if (cleanWord === key || (cleanWord.length > 3 && key.length > 3 && (cleanWord.includes(key) || key.includes(cleanWord)))) {
      return url;
    }
  }

  // 5. Match by English meaning words (e.g. "coffee", "apple", "bread")
  const rawMeaning = (vocab.meaningEn || '').toLowerCase();
  const meaningTokens = rawMeaning
    .replace(/^(the|a|an|to)s+/i, '')
    .split(/[\s,/;()]+/)
    .map((t) => t.trim())
    .filter(Boolean);

  for (const token of meaningTokens) {
    if (ENGLISH_KEYWORD_IMAGE_MAP[token]) {
      return ENGLISH_KEYWORD_IMAGE_MAP[token];
    }
  }

  // Check substring in meaning
  for (const [key, url] of Object.entries(ENGLISH_KEYWORD_IMAGE_MAP)) {
    if (rawMeaning.includes(key)) {
      return url;
    }
  }

  // 6. Dynamic Generative Photo Resolver for ANY arbitrary newly added word
  const cleanPromptWord = (vocab.meaningEn || cleanWord || '')
    .replace(/^(the|a|an|to)s+/i, '')
    .replace(/[^a-zA-Z0-9\s]/g, '')
    .trim();

  if (cleanPromptWord && cleanPromptWord.length > 1) {
    return `https://image.pollinations.ai/prompt/${encodeURIComponent('high quality realistic photo of ' + cleanPromptWord)}?width=600&height=400&nologo=true`;
  }

  // 7. Topic-specific fallback (diverse curated photos)
  const topic = (vocab.topic || '').toLowerCase();
  if (topic.includes('essen') || topic.includes('appetit') || topic.includes('trinken')) {
    return 'https://images.unsplash.com/photo-1504674900247-0877df9cc836?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('wohnung') || topic.includes('möbel') || topic.includes('umzug') || topic.includes('wohnen')) {
    return 'https://images.unsplash.com/photo-1502672260266-1c1ef2d93688?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('stadt') || topic.includes('reise') || topic.includes('verkehr')) {
    return 'https://images.unsplash.com/photo-1477959858617-67f30bc75b82?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('gesund') || topic.includes('fit') || topic.includes('körper')) {
    return 'https://images.unsplash.com/photo-1517838277536-f5f99be501cd?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('arbeit') || topic.includes('beruf')) {
    return 'https://images.unsplash.com/photo-1497215728101-856f4ea42174?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('einkaufen') || topic.includes('kleidung')) {
    return 'https://images.unsplash.com/photo-1483985988355-763728e1935b?auto=format&fit=crop&w=600&q=80';
  }
  if (topic.includes('freizeit') || topic.includes('hobby') || topic.includes('zeit mit')) {
    return 'https://images.unsplash.com/photo-1499209974431-9dddcece7f88?auto=format&fit=crop&w=600&q=80';
  }

  // 8. Standard Germany / Learning Hero Fallback
  return 'https://images.unsplash.com/photo-1467269204594-9661b134dd2b?auto=format&fit=crop&w=600&q=80';
}